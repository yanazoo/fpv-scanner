#!/usr/bin/env python3
"""Generate src/lcd_font.h, the bitmap font of the touch-LCD build.

Glyphs come from GNU Unifont (unifont_jp.otf, Debian package fonts-unifont;
GPL-2.0+ with the font embedding exception / SIL OFL 1.1): 8x16 for ASCII and
the narrow symbols, 16x16 for Japanese. Only ASCII and the non-ASCII
characters that appear in the scanned sources are included, so after adding
Japanese text to the LCD screens run:

    python3 tools/gen_font.py
"""
import pathlib
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = "/usr/share/fonts/opentype/unifont/unifont_jp.otf"
SOURCES = ["src/lcd_ui.cpp", "src/main.cpp"]


def glyph(font, ch):
    width = int(font.getlength(ch))
    if width not in (8, 16):
        sys.exit(f"unexpected width {width} for {ch!r}")
    image = Image.new("1", (16, 16), 0)
    ImageDraw.Draw(image).text((0, 0), ch, font=font, fill=1, anchor="la")
    rows = []
    for y in range(16):
        bits = 0
        for x in range(width):
            if image.getpixel((x, y)):
                bits |= 1 << (width - 1 - x)
        rows += [bits >> 8, bits & 0xFF] if width == 16 else [bits]
    return width, rows


def main():
    text = "".join((ROOT / s).read_text(encoding="utf-8") for s in SOURCES)
    wide = sorted({c for c in text if ord(c) > 0x7E and ord(c) <= 0xFFFF})
    chars = [chr(c) for c in range(0x20, 0x7F)] + wide
    font = ImageFont.truetype(FONT, 16)
    data, index = [], []
    for ch in chars:
        width, rows = glyph(font, ch)
        index.append((ord(ch), width, len(data)))
        data += rows
    out = [
        "#pragma once",
        "/* Generated by tools/gen_font.py from GNU Unifont (unifont_jp.otf). */",
        "#include <stdint.h>",
        "",
        "struct LcdGlyph {",
        "    uint16_t code;",
        "    uint8_t width; /* 8: one byte per row, 16: two bytes per row */",
        "    uint16_t offset;",
        "};",
        "",
        "static const uint8_t lcd_font_bits[] = {",
    ]
    for i in range(0, len(data), 16):
        out.append("    " + ", ".join(f"0x{b:02x}" for b in data[i : i + 16]) + ",")
    out += ["};", "", "/* Sorted by code for binary search. */", "static const LcdGlyph lcd_font_glyphs[] = {"]
    for code, width, offset in index:
        out.append(f"    {{0x{code:04x}, {width}, {offset}}}, /* {chr(code) if code != 0x5c else 'backslash'} */")
    out += ["};", f"static const unsigned lcd_font_count = {len(index)};", ""]
    (ROOT / "src/lcd_font.h").write_text("\n".join(out), encoding="utf-8")
    print(f"{len(index)} glyphs ({len(wide)} non-ASCII), {len(data)} bytes")


if __name__ == "__main__":
    main()
